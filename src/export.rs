#![forbid(unsafe_code)]

//! Pure-Rust Archival Document Export (`DOCX` & `PDF`).
//!
//! - `DOCX` uses OOXML (`zip` + UTF-8 XML with native `<w:bidi/>` & `<w:rtl/>`) so both
//!   Original Jawi (RTL) and Standard Bahasa Malaysia (Rumi) render crisply in Microsoft Word
//!   and LibreOffice Writer.
//! - `PDF` uses `lopdf` to build a clean, word-wrapped, multi-page A4 archival PDF with
//!   metadata, Hijri-to-Masihi colophon dates, Rumi transcription, summary, and notes.

use chrono::Utc;
use lopdf::content::{Content, Operation};
use lopdf::{Document, Object, Stream, dictionary};
use serde_json::Value;
use std::io::{Cursor, Write};
use zip::write::SimpleFileOptions;
use zip::{CompressionMethod, ZipWriter};

#[derive(Clone, Debug, Default)]
pub struct ExportDocumentInput {
    pub title: String,
    pub reference_code: String,
    pub group: String,
    pub script_type: String,
    pub verified_by_human: bool,
    pub hijri_date: String,
    pub gregorian_date_masihi: String,
    pub jawi_text: String,
    pub rumi_text: String,
    pub summary: String,
    pub notes: String,
}

impl ExportDocumentInput {
    pub fn from_doc_value(doc: &Value) -> Self {
        let s = |k: &str| -> String {
            doc.get(k)
                .and_then(Value::as_str)
                .unwrap_or("")
                .trim()
                .to_string()
        };
        let title = {
            let t = s("title");
            if t.is_empty() {
                "Archival Document".to_string()
            } else {
                t
            }
        };
        Self {
            title,
            reference_code: s("reference_code"),
            group: s("group"),
            script_type: s("script_type"),
            verified_by_human: doc
                .get("verified_by_human")
                .and_then(Value::as_bool)
                .unwrap_or(false),
            hijri_date: s("hijri_date"),
            gregorian_date_masihi: s("gregorian_date_masihi"),
            jawi_text: s("jawi_text"),
            rumi_text: s("extracted_text"),
            summary: s("summary"),
            notes: s("notes"),
        }
    }
}

fn xml_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&apos;"),
            c if c.is_control() && c != '\t' && c != '\n' && c != '\r' => {}
            other => out.push(other),
        }
    }
    out
}

fn docx_heading(text: &str, size_half_pt: u32, color_hex: &str) -> String {
    let esc = xml_escape(text);
    format!(
        "<w:p><w:pPr><w:spacing w:before=\"200\" w:after=\"100\"/></w:pPr>\
         <w:r><w:rPr><w:b/><w:color w:val=\"{color_hex}\"/><w:sz w:val=\"{size_half_pt}\"/><w:szCs w:val=\"{size_half_pt}\"/></w:rPr>\
         <w:t xml:space=\"preserve\">{esc}</w:t></w:r></w:p>"
    )
}

fn docx_para(text: &str) -> String {
    let esc = xml_escape(text);
    format!(
        "<w:p><w:pPr><w:spacing w:after=\"100\"/></w:pPr>\
         <w:r><w:rPr><w:rFonts w:ascii=\"Calibri\" w:hAnsi=\"Calibri\"/><w:sz w:val=\"22\"/></w:rPr>\
         <w:t xml:space=\"preserve\">{esc}</w:t></w:r></w:p>"
    )
}

fn docx_kv(label: &str, value: &str) -> String {
    let l = xml_escape(label);
    let v = xml_escape(value);
    format!(
        "<w:p><w:pPr><w:spacing w:after=\"60\"/></w:pPr>\
         <w:r><w:rPr><w:b/><w:color w:val=\"334155\"/><w:sz w:val=\"20\"/></w:rPr><w:t xml:space=\"preserve\">{l}: </w:t></w:r>\
         <w:r><w:rPr><w:sz w:val=\"20\"/></w:rPr><w:t xml:space=\"preserve\">{v}</w:t></w:r></w:p>"
    )
}

fn docx_rtl_jawi_para(line: &str) -> String {
    let esc = xml_escape(line);
    format!(
        "<w:p><w:pPr><w:bidi/><w:jc w:val=\"right\"/><w:spacing w:after=\"120\"/></w:pPr>\
         <w:r><w:rPr><w:rFonts w:ascii=\"Traditional Arabic\" w:hAnsi=\"Traditional Arabic\" w:cs=\"Traditional Arabic\"/>\
         <w:rtl/><w:sz w:val=\"30\"/><w:szCs w:val=\"34\"/></w:rPr>\
         <w:t xml:space=\"preserve\">{esc}</w:t></w:r></w:p>"
    )
}

/// Generates a spec-compliant `.docx` (OOXML) file in pure safe Rust with native RTL Jawi
/// paragraphs, Standard Bahasa Malaysia (Rumi) text, Hijri-to-Masihi dates, and archival metadata.
pub fn build_docx_bytes(doc: &ExportDocumentInput) -> Result<Vec<u8>, String> {
    let mut body = String::with_capacity(4096);
    body.push_str(&docx_heading(&doc.title, 36, "1E3A8A"));
    body.push_str(&docx_kv(
        "Generated By",
        &format!(
            "ArkibVision Archival Platform ({})",
            Utc::now().format("%Y-%m-%d %H:%M UTC")
        ),
    ));
    if !doc.reference_code.is_empty() {
        body.push_str(&docx_kv("Reference Code", &doc.reference_code));
    }
    if !doc.group.is_empty() {
        body.push_str(&docx_kv("Group Folder", &doc.group));
    }
    if !doc.script_type.is_empty() {
        body.push_str(&docx_kv("Script Type", &doc.script_type));
    }
    if doc.verified_by_human {
        body.push_str(&docx_kv(
            "Verification Status",
            "Human-Verified Archival Transcription",
        ));
    }
    if !doc.hijri_date.is_empty() {
        let combined = if doc.gregorian_date_masihi.is_empty() {
            doc.hijri_date.clone()
        } else {
            format!("{} (Masihi: {})", doc.hijri_date, doc.gregorian_date_masihi)
        };
        body.push_str(&docx_kv("Colophon Date (Hijri / Masihi)", &combined));
    }

    if !doc.jawi_text.trim().is_empty() {
        body.push_str(&docx_heading(
            "Original Jawi Text (Teks Jawi Asal)",
            26,
            "1E3A8A",
        ));
        for line in doc.jawi_text.lines() {
            if !line.trim().is_empty() {
                body.push_str(&docx_rtl_jawi_para(line.trim()));
            }
        }
    }

    if !doc.rumi_text.trim().is_empty() {
        body.push_str(&docx_heading(
            "Standard Bahasa Malaysia Transcription (Rumi)",
            26,
            "1E3A8A",
        ));
        for line in doc.rumi_text.lines() {
            if !line.trim().is_empty() {
                body.push_str(&docx_para(line.trim()));
            }
        }
    }

    if !doc.summary.trim().is_empty() {
        body.push_str(&docx_heading(
            "Archival Summary (Ringkasan Arkib)",
            26,
            "1E3A8A",
        ));
        for line in doc.summary.lines() {
            if !line.trim().is_empty() {
                body.push_str(&docx_para(line.trim()));
            }
        }
    }

    if !doc.notes.trim().is_empty() {
        body.push_str(&docx_heading("Archivist Notes (Catatan)", 24, "334155"));
        for line in doc.notes.lines() {
            if !line.trim().is_empty() {
                body.push_str(&docx_para(line.trim()));
            }
        }
    }

    let document_xml = format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\
         <w:document xmlns:w=\"http://schemas.openxmlformats.org/wordprocessingml/2006/main\">\
         <w:body>{body}<w:sectPr><w:pgSz w:w=\"11906\" w:h=\"16838\"/>\
         <w:pgMar w:top=\"1440\" w:right=\"1440\" w:bottom=\"1440\" w:left=\"1440\"/></w:sectPr>\
         </w:body></w:document>"
    );

    let content_types = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
</Types>"#;

    let root_rels = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>"#;

    let doc_rels = r#"<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"/>"#;

    let mut cursor = Cursor::new(Vec::new());
    {
        let mut zip = ZipWriter::new(&mut cursor);
        let opts = SimpleFileOptions::default().compression_method(CompressionMethod::Deflated);

        zip.start_file("[Content_Types].xml", opts)
            .map_err(|e| format!("DOCX zip error: {e}"))?;
        zip.write_all(content_types.as_bytes())
            .map_err(|e| format!("DOCX write error: {e}"))?;

        zip.start_file("_rels/.rels", opts)
            .map_err(|e| format!("DOCX zip error: {e}"))?;
        zip.write_all(root_rels.as_bytes())
            .map_err(|e| format!("DOCX write error: {e}"))?;

        zip.start_file("word/_rels/document.xml.rels", opts)
            .map_err(|e| format!("DOCX zip error: {e}"))?;
        zip.write_all(doc_rels.as_bytes())
            .map_err(|e| format!("DOCX write error: {e}"))?;

        zip.start_file("word/document.xml", opts)
            .map_err(|e| format!("DOCX zip error: {e}"))?;
        zip.write_all(document_xml.as_bytes())
            .map_err(|e| format!("DOCX write error: {e}"))?;

        zip.finish()
            .map_err(|e| format!("DOCX finish error: {e}"))?;
    }
    Ok(cursor.into_inner())
}

fn sanitize_pdf_latin(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            '–' | '—' => '-',
            '‘' | '’' => '\'',
            '“' | '”' => '"',
            '•' => '*',
            '→' => '>',
            c if (32..=126).contains(&(c as u32)) => c,
            c if ('\u{00A0}'..='\u{00FF}').contains(&c) => c,
            _ => ' ',
        })
        .collect::<String>()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

fn wrap_pdf_lines(text: &str, max_chars: usize) -> Vec<String> {
    let mut out = Vec::new();
    for raw_line in text.lines() {
        let clean = sanitize_pdf_latin(raw_line);
        if clean.is_empty() {
            continue;
        }
        let mut current = String::new();
        for word in clean.split_whitespace() {
            if current.is_empty() {
                current.push_str(word);
            } else if current.len() + 1 + word.len() <= max_chars {
                current.push(' ');
                current.push_str(word);
            } else {
                out.push(current);
                current = word.to_string();
            }
        }
        if !current.is_empty() {
            out.push(current);
        }
    }
    out
}

enum PdfLine {
    Title(String),
    Heading(String),
    Meta(String),
    Body(String),
    Spacer,
}

/// Generates a clean, multi-page A4 archival `.pdf` in pure safe Rust via `lopdf`.
pub fn build_pdf_bytes(doc: &ExportDocumentInput) -> Result<Vec<u8>, String> {
    let mut items: Vec<PdfLine> = Vec::new();
    for l in wrap_pdf_lines(&doc.title, 48) {
        items.push(PdfLine::Title(l));
    }
    items.push(PdfLine::Meta(format!(
        "ArkibVision Archival Record | Generated: {}",
        Utc::now().format("%Y-%m-%d %H:%M UTC")
    )));
    if !doc.reference_code.is_empty() {
        items.push(PdfLine::Meta(format!(
            "Reference Code: {}",
            sanitize_pdf_latin(&doc.reference_code)
        )));
    }
    if !doc.group.is_empty() {
        items.push(PdfLine::Meta(format!(
            "Group Folder: {}",
            sanitize_pdf_latin(&doc.group)
        )));
    }
    if !doc.script_type.is_empty() {
        items.push(PdfLine::Meta(format!(
            "Script Type: {}",
            sanitize_pdf_latin(&doc.script_type)
        )));
    }
    if doc.verified_by_human {
        items.push(PdfLine::Meta(
            "Verification: Human-Verified Archival Transcription".to_string(),
        ));
    }
    if !doc.hijri_date.is_empty() {
        let combined = if doc.gregorian_date_masihi.is_empty() {
            sanitize_pdf_latin(&doc.hijri_date)
        } else {
            format!(
                "{} (Masihi: {})",
                sanitize_pdf_latin(&doc.hijri_date),
                sanitize_pdf_latin(&doc.gregorian_date_masihi)
            )
        };
        items.push(PdfLine::Meta(format!("Colophon Date: {combined}")));
    }
    items.push(PdfLine::Spacer);

    if !doc.rumi_text.trim().is_empty() {
        items.push(PdfLine::Heading(
            "Standard Bahasa Malaysia Transcription (Rumi)".to_string(),
        ));
        for l in wrap_pdf_lines(&doc.rumi_text, 84) {
            items.push(PdfLine::Body(l));
        }
        items.push(PdfLine::Spacer);
    }

    if !doc.summary.trim().is_empty() {
        items.push(PdfLine::Heading(
            "Archival Summary (Ringkasan Arkib)".to_string(),
        ));
        for l in wrap_pdf_lines(&doc.summary, 84) {
            items.push(PdfLine::Body(l));
        }
        items.push(PdfLine::Spacer);
    }

    if !doc.notes.trim().is_empty() {
        items.push(PdfLine::Heading("Archivist Notes (Catatan)".to_string()));
        for l in wrap_pdf_lines(&doc.notes, 84) {
            items.push(PdfLine::Body(l));
        }
        items.push(PdfLine::Spacer);
    }

    if !doc.jawi_text.trim().is_empty() {
        items.push(PdfLine::Meta(
            "Note: Original RTL Jawi Unicode script is preserved natively in the DOCX export."
                .to_string(),
        ));
    }

    // Paginate cleanly across A4 (595 x 842 pt)
    let mut pages_ops: Vec<Vec<Operation>> = Vec::new();
    let mut cur_ops: Vec<Operation> = Vec::new();
    let mut y: f32 = 790.0;

    let start_page = |ops: &mut Vec<Operation>| {
        // Subtle royal-blue top accent rule
        ops.push(Operation::new(
            "rg",
            vec![0.12.into(), 0.23.into(), 0.54.into()],
        ));
        ops.push(Operation::new(
            "re",
            vec![50.into(), 814.into(), 495.into(), 4.into()],
        ));
        ops.push(Operation::new("f", vec![]));
        ops.push(Operation::new(
            "rg",
            vec![0.08.into(), 0.09.into(), 0.12.into()],
        ));
    };
    start_page(&mut cur_ops);

    for item in items {
        let (font, size, step, text_opt) = match item {
            PdfLine::Title(t) => ("F2", 16.0_f32, 22.0_f32, Some(t)),
            PdfLine::Heading(t) => ("F2", 12.0_f32, 18.0_f32, Some(t)),
            PdfLine::Meta(t) => ("F1", 9.5_f32, 14.0_f32, Some(t)),
            PdfLine::Body(t) => ("F1", 10.5_f32, 15.0_f32, Some(t)),
            PdfLine::Spacer => ("F1", 10.0_f32, 10.0_f32, None),
        };
        if y - step < 56.0 {
            pages_ops.push(cur_ops);
            cur_ops = Vec::new();
            y = 790.0;
            start_page(&mut cur_ops);
        }
        if let Some(txt) = text_opt {
            cur_ops.push(Operation::new("BT", vec![]));
            cur_ops.push(Operation::new("Tf", vec![font.into(), size.into()]));
            cur_ops.push(Operation::new("Td", vec![50.0.into(), y.into()]));
            cur_ops.push(Operation::new("Tj", vec![Object::string_literal(txt)]));
            cur_ops.push(Operation::new("ET", vec![]));
        }
        y -= step;
    }
    pages_ops.push(cur_ops);

    let mut pdf = Document::with_version("1.5");
    let pages_id = pdf.new_object_id();
    let font_regular = pdf.add_object(dictionary! {
        "Type" => "Font",
        "Subtype" => "Type1",
        "BaseFont" => "Helvetica",
        "Encoding" => "WinAnsiEncoding",
    });
    let font_bold = pdf.add_object(dictionary! {
        "Type" => "Font",
        "Subtype" => "Type1",
        "BaseFont" => "Helvetica-Bold",
        "Encoding" => "WinAnsiEncoding",
    });
    let resources_id = pdf.add_object(dictionary! {
        "Font" => dictionary! {
            "F1" => font_regular,
            "F2" => font_bold,
        },
    });

    let total_pages = pages_ops.len();
    let mut kids: Vec<Object> = Vec::with_capacity(total_pages);
    for (idx, mut ops) in pages_ops.into_iter().enumerate() {
        // Page number footer
        ops.push(Operation::new("BT", vec![]));
        ops.push(Operation::new("Tf", vec!["F1".into(), 8.5_f32.into()]));
        ops.push(Operation::new("Td", vec![50.0.into(), 30.0.into()]));
        ops.push(Operation::new(
            "Tj",
            vec![Object::string_literal(format!(
                "ArkibVision Archive  |  Page {} of {}",
                idx + 1,
                total_pages
            ))],
        ));
        ops.push(Operation::new("ET", vec![]));

        let content = Content { operations: ops };
        let encoded = content
            .encode()
            .map_err(|e| format!("PDF content encode error: {e}"))?;
        let content_id = pdf.add_object(Stream::new(dictionary! {}, encoded));
        let page_id = pdf.add_object(dictionary! {
            "Type" => "Page",
            "Parent" => pages_id,
            "Contents" => content_id,
            "Resources" => resources_id,
            "MediaBox" => vec![0.into(), 0.into(), 595.into(), 842.into()],
        });
        kids.push(page_id.into());
    }

    pdf.objects.insert(
        pages_id,
        Object::Dictionary(dictionary! {
            "Type" => "Pages",
            "Kids" => kids,
            "Count" => total_pages as i64,
        }),
    );
    let catalog_id = pdf.add_object(dictionary! {
        "Type" => "Catalog",
        "Pages" => pages_id,
    });
    pdf.trailer.set("Root", catalog_id);

    let mut out = Vec::new();
    pdf.save_to(&mut out)
        .map_err(|e| format!("PDF save error: {e}"))?;
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Read;

    #[test]
    fn test_docx_and_pdf_export_roundtrip() {
        let sample = ExportDocumentInput {
            title: "Surat Sultan 1324H".into(),
            reference_code: "ANM-JAWI-1324".into(),
            group: "Historical Manuscripts".into(),
            script_type: "jawi".into(),
            verified_by_human: true,
            hijri_date: "13 Muharam 1324H".into(),
            gregorian_date_masihi: "1906-03-09".into(),
            jawi_text: "مک تتکال ايت سݢل راج٢ برهيمڤون دباليروڠ سري".into(),
            rumi_text: "Maka tatkala itu segala raja-raja berhimpun di balairung seri.".into(),
            summary: "Historical royal assembly record from 1906.".into(),
            notes: "Verified by archivist.".into(),
        };

        // 1. DOCX round-trip verifies RTL Jawi + Rumi + Hijri/Masihi
        let docx_bytes = build_docx_bytes(&sample).unwrap();
        let mut zip = zip::ZipArchive::new(Cursor::new(&docx_bytes)).unwrap();
        let mut xml = String::new();
        zip.by_name("word/document.xml")
            .unwrap()
            .read_to_string(&mut xml)
            .unwrap();
        assert!(xml.contains("<w:bidi/>"));
        assert!(xml.contains("<w:rtl/>"));
        assert!(xml.contains("سݢل راج٢"));
        assert!(xml.contains("Maka tatkala itu"));
        assert!(xml.contains("13 Muharam 1324H"));

        // 2. PDF round-trip via lopdf verifies clean A4 PDF with extractable Rumi & metadata
        let pdf_bytes = build_pdf_bytes(&sample).unwrap();
        let loaded = Document::load_mem(&pdf_bytes).unwrap();
        let extracted = loaded.extract_text(&[1]).unwrap();
        assert!(extracted.contains("Surat Sultan 1324H"));
        assert!(extracted.contains("Maka tatkala itu"));
        assert!(extracted.contains("1906-03-09"));
    }
}
